EDIT = [('C1', 1, 45, 15), ('N1', 481, 510, 15), ('C2', 46, 75, 15), ('N2', 511, 540, 15), ('N3a', 541, 555, 15), ('N3b', 556, 570, 15),
        ('C3', 76, 90, 15), ('C4', 91, 102, 15), ('C5', 103, 150, 30), ('C6', 151, 189, 30), ('C7', 190, 231, 15), ('N4', 586, 615, 15),
        ('C8', 232, 273, 15), ('N5', 616, 675, 15), ('C9', 274, 306, 15), ('C10', 307, 339, 15), ('N6a', 676, 690, 15), ('N6b', 691, 705, 15),
        ('C11', 340, 363, 15), ('C12', 364, 405, 15), ('C13', 406, 450, 15), ('N7', 706, 735, 15), ('C14', 451, 480, 15)]
def edit_time(gf):
    t = 0.0
    for s, a, b, _ in EDIT:
        if a <= gf <= b: return t + (gf - a) / 30.0
        t += (b - a + 1) / 30.0
    return None
TOTAL = sum((b - a + 1) for _, a, b, _ in EDIT) / 30.0
if __name__ == '__main__':
    import sys
    if sys.argv[1] == 'list':
        for s, a, b, fps in EDIT: print(s, fps, '%.4f' % ((b - a + 1) / 30.0))
    print('TOTAL', TOTAL, file=sys.stderr)
